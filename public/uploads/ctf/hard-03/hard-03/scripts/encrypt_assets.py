"""Encrypt the challenge assets and emit src/generated_assets.h.

Pipeline (Stage 4 + Stage 5 of the challenge spec):
  1. ChaCha20-encrypt the raw flag using a random key + nonce (Stage 5).
     The ChaCha20 key is discarded; it is later re-derived at runtime
     from SHA1 of the AES plaintext, so it must equal that value here.
  2. Build a JSON blob:  {"nonce": "<hex>", "flag": "<hex ciphertext>"}
  3. Base85-encode the JSON.
  4. AES-256-CBC-encrypt the Base85 string with the random AES key + IV.
  5. Embed only the AES ciphertext (plus obfuscated key material) in the
     generated C header.

Dependencies:  pip install cryptography pycryptodome
"""
from __future__ import annotations

import base64
import hashlib
import json
from pathlib import Path

from Crypto.Cipher import AES, ChaCha20
from Crypto.Util.Padding import pad

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
KEYS = json.loads((HERE / "keys.json").read_text())
OUT = ROOT / "src" / "generated_assets.h"

# Byte indices from SHA256(seed) used to reconstruct the last 8 bytes of
# the AES key at runtime. MUST match crypto.cpp::reconstruct_tail().
TAIL_INDICES = (3, 7, 12, 18, 23, 29, 30, 31)


def hex_array(name: str, data: bytes) -> str:
    body = ", ".join(f"0x{b:02X}" for b in data)
    return f"static const unsigned char {name}[{len(data)}] = {{ {body} }};"


def xor_bytes(data: bytes, mask: bytes) -> bytes:
    return bytes(b ^ mask[i % len(mask)] for i, b in enumerate(data))


def main() -> None:
    aes_key = bytes.fromhex(KEYS["aes_key"])
    aes_iv = bytes.fromhex(KEYS["aes_iv"])
    nonce = bytes.fromhex(KEYS["chacha_nonce"])
    flag = KEYS["flag"].encode()

    assert len(aes_key) == 32
    assert len(aes_iv) == 16
    assert len(nonce) == 12

    # ── Stage 5: ChaCha20 encrypt the flag ────────────────────────────
    # The runtime derives the ChaCha20 key as SHA1(aes_plaintext). To
    # make the chain solvable, the AES plaintext IS the source of that
    # key. So we build the AES plaintext (Base85 of JSON) first, take
    # its SHA1, and use that as the ChaCha20 key.

    # Structure of the JSON we'll encrypt with AES:
    payload_template = {"nonce": nonce.hex(), "flag": None}

    # We need aes_plaintext bytes -> ChaCha20 key = SHA1(aes_plaintext).
    # But aes_plaintext depends on the ChaCha20 ciphertext of the flag.
    # Break the circularity: choose a placeholder JSON to compute the
    # AES plaintext + SHA1, encrypt the flag with that key, then
    # substitute the real ciphertext.
    placeholder = dict(payload_template, flag="00" * len(flag))
    placeholder_json = json.dumps(placeholder, separators=(",", ":")).encode()
    aes_plaintext = base64.b85encode(placeholder_json)
    chacha_key = hashlib.sha1(aes_plaintext).digest()[:32].ljust(32, b"\0")

    cipher = ChaCha20.new(key=chacha_key, nonce=nonce)
    flag_ct = cipher.encrypt(flag)

    # Substitute real ciphertext and re-serialize. Because we preserved
    # length and structure, SHA1(aes_plaintext) is unchanged.
    payload = dict(payload_template, flag=flag_ct.hex())
    payload_json = json.dumps(payload, separators=(",", ":")).encode()
    aes_plaintext_final = base64.b85encode(payload_json)
    assert hashlib.sha1(aes_plaintext_final).digest()[:32].ljust(32, b"\0") == chacha_key

    # ── Stage 4: AES-256-CBC encrypt the Base85 blob ──────────────────
    aes = AES.new(aes_key, AES.MODE_CBC, aes_iv)
    aes_ct = aes.encrypt(pad(aes_plaintext_final, AES.block_size))

    # ── Stage 3 storage: first 24 bytes of key are XOR-obfuscated ─────
    XOR_MASK = b"SpiderSociety-2026-Auditor"
    key_head = xor_bytes(aes_key[:24], XOR_MASK)

    # Sanity: recomputing tail bytes from SHA256("seed") is done at
    # runtime with the actual seed. Here we just document indices used.
    tail_bytes = aes_key[24:]

    # ── Emit header ───────────────────────────────────────────────────
    lines = [
        "// AUTO-GENERATED by scripts/encrypt_assets.py — do not hand-edit.",
        "#pragma once",
        "",
        "// XOR-obfuscated first 24 bytes of the AES-256 key.",
        hex_array("g_key_head_obf", key_head),
        "",
        "// XOR mask used to recover g_key_head_obf.",
        hex_array("g_key_head_mask", XOR_MASK),
        "",
        "// AES-256-CBC IV.",
        hex_array("g_aes_iv", aes_iv),
        "",
        "// AES-256-CBC ciphertext of the Base85-encoded JSON payload.",
        hex_array("g_aes_ct", aes_ct),
        "",
        "// SHA256(seed) byte indices used to reconstruct the AES key tail.",
        "static const unsigned int g_tail_indices[8] = { "
        + ", ".join(str(i) for i in TAIL_INDICES) + " };",
        "",
        "// Reference-only: the true tail bytes (used by the build to embed",
        "// a *decoy* tail; the real tail is reconstructed at runtime).",
        hex_array("g_tail_decoy",
                  bytes((b ^ 0x5A) for b in tail_bytes)),
        "",
        "// Decoy artefacts (Stage 7) — dead ends for reverse engineers.",
        f"static const char g_decoy_flag_a[] = \"SPIDER{{fake_ledger_v1}}\";",
        f"static const char g_decoy_flag_b[] = \"SPIDER{{auditor_test_flag}}\";",
        f"static const char g_decoy_json[]   = \"{{\\\"flag\\\":\\\"NOPE\\\"}}\";",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")

    # Also emit a small manifest for the build log (not embedded).
    manifest = {
        "aes_ct_len": len(aes_ct),
        "aes_pt_len": len(aes_plaintext_final),
        "flag_ct_len": len(flag_ct),
        "chacha_key_source": "SHA1(aes_plaintext) padded to 32 bytes",
    }
    (HERE / "assets_manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"wrote {OUT}")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
